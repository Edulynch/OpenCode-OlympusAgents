    Check AT25 ($k -match 'MAX_ACTIVE_CHILDREN = 4' -and $k -match 'Four is a ceiling, never a target' -and $k -notmatch 'gpt-6-luna#fast')
    Check AT26 (-not (Test-Path (Join-Path $source '.opencode/agents/sorin.md')) -and $b -match "'sorin'" -and $a -notmatch 'gpt-6-luna#fast')

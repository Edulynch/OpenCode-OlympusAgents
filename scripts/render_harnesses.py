#!/usr/bin/env python3
"""Render the OpenCode Olympus runtime adapter from checked-in sources."""

from __future__ import annotations

import argparse
import json
import os
import re
import stat
import sys
import tomllib
from pathlib import Path


CAPABILITIES = (
    "ROOT_ORCHESTRATOR",
    "CUSTOM_SPECIALISTS",
    "PER_ROLE_MODEL",
    "PER_ROLE_REASONING",
    "MULTI_AGENT",
    "BOUNDED_PARALLELISM",
    "QUESTION_CENTRALIZATION",
    "COMPLETION_BARRIER",
    "RESULT_DELIVERY",
    "RESULT_RECONCILIATION",
    "ALLOW",
    "ASK",
    "DENY",
    "CONTEXTUAL_OLYMPUS_MAINTENANCE",
    "ACTIVITY_VISIBILITY",
    "GLOBAL_RUNTIME_DISCOVERY",
)
VALID_STATES = {"SUPPORTED", "ADAPTABLE", "PARTIAL", "GAP", "NOT_NEEDED"}
GENERATED = "GENERATED BY scripts/render_harnesses.py — edit Olympus Core/adapter sources, not this output."

# Only immediate children in these renderer-owned namespaces are eligible.
# The top-level config and capability document are fixed singleton outputs.
OPENCODE_OUTPUT_NAMESPACES = {
    Path(".opencode/agents"): {".md"},
    Path(".opencode/commands"): {".md"},
    Path(".opencode/plugins/olympus-activity"): {".ts", ".tsx"},
    Path(".opencode/scripts"): {".ps1"},
}


class RenderError(Exception):
    pass


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise RenderError(f"cannot read {path}: {error}") from error


def read_toml(path: Path) -> dict:
    try:
        with path.open("rb") as stream:
            return tomllib.load(stream)
    except (OSError, tomllib.TOMLDecodeError) as error:
        raise RenderError(f"cannot parse {path}: {error}") from error


def role_ids(root: Path) -> set[str]:
    roles = root / "olympus" / "roles"
    ids = {path.stem for path in roles.glob("*.md") if path.is_file()}
    if not ids:
        raise RenderError(f"no canonical roles found under {roles}")
    return ids


def checked_sources(root: Path) -> tuple[dict, dict, dict, dict[str, str], set[str]]:
    models = read_toml(root / "olympus" / "core" / "models.toml")
    identity_source = read_toml(root / "olympus" / "core" / "identities.toml")
    policies = read_toml(root / "olympus" / "policies" / "orchestration.toml")
    capabilities = read_toml(root / "olympus" / "harnesses" / "capabilities.toml")
    roles = role_ids(root)
    model_roles = set(models.get("roles", {}))
    if roles != model_roles:
        raise RenderError(
            "canonical role roster differs between olympus/roles and olympus/core/models.toml: "
            f"roles-only={sorted(roles - model_roles)}, models-only={sorted(model_roles - roles)}"
        )
    identities = {role: value.get("display", "").strip() for role, value in identity_source.get("roles", {}).items()}
    if set(identities) != roles or any(not display for display in identities.values()):
        raise RenderError(
            "canonical identity roster differs from canonical roles: "
            f"missing={sorted(roles - set(identities))}, unexpected={sorted(set(identities) - roles)}"
        )
    if len({display.casefold() for display in identities.values()}) != len(identities):
        raise RenderError("canonical display identities must be unique")
    for role, display in identities.items():
        if display.split(" — ", 1)[0].casefold() != role.casefold() or " — " not in display:
            raise RenderError(f"canonical display identity for {role!r} must preserve its technical ID")
    for family, info in models.get("families", {}).items():
        if isinstance(info, dict) and "codex" in info:
            raise RenderError(f"Codex model mapping is unsupported in family {family!r}")
        if not isinstance(info, dict) or set(info) != {"opencode"} or not info["opencode"]:
            raise RenderError(f"model family {family!r} needs one OpenCode identifier")
    for role, info in models["roles"].items():
        if info.get("family") not in models["families"] or not info.get("effort"):
            raise RenderError(f"incomplete canonical model intent for role {role!r}")
    if not isinstance(policies.get("max_children"), int) or policies["max_children"] < 1:
        raise RenderError("olympus/policies/orchestration.toml must define positive integer max_children")
    if "codex" in capabilities:
        raise RenderError("Codex capability table is unsupported; declare only the OpenCode adapter")
    if set(capabilities) != {"opencode"}:
        raise RenderError("capability contract must declare exactly the OpenCode adapter")
    for harness, values in capabilities.items():
        if set(values) != set(CAPABILITIES):
            raise RenderError(
                f"{harness} capability IDs differ: missing={sorted(set(CAPABILITIES) - set(values))}, "
                f"unexpected={sorted(set(values) - set(CAPABILITIES))}"
            )
        invalid = {name: state for name, state in values.items() if state not in VALID_STATES}
        if invalid:
            raise RenderError(f"invalid {harness} capability state(s): {invalid}")
    return models, policies, capabilities, identities, roles


def role_model(models: dict, role: str) -> tuple[str, str]:
    try:
        role_intent = models["roles"][role]
        family = models["families"][role_intent["family"]]
        model = family["opencode"]
        effort = role_intent["effort"]
    except KeyError as error:
        raise RenderError(f"missing OpenCode model intent for {role}: {error}") from error
    return model, effort


def replace_tokens(text: str, values: dict[str, object], source: Path) -> str:
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", str(value))
    unresolved = sorted(set(re.findall(r"\{\{[A-Za-z0-9_]+\}\}", text)))
    if unresolved:
        raise RenderError(f"unresolved template token(s) in {source}: {', '.join(unresolved)}")
    return text


def markdown_section(text: str, heading: str, source: Path) -> str:
    lines = text.splitlines()
    try:
        start = next(index for index, line in enumerate(lines) if line.strip() == heading)
    except StopIteration as error:
        raise RenderError(f"missing {heading!r} in {source}") from error
    end = next((index for index in range(start + 1, len(lines)) if lines[index].startswith("#")), len(lines))
    return "\n".join(lines[start:end]).strip()


def focused_testing_policy(root: Path) -> str:
    """Use the one canonical testing policy in both root-agent adapters."""
    source = root / "olympus" / "policies" / "routing.md"
    canonical = read_text(source)
    heading = "## TFR — risk-based focused testing"
    if canonical.count(heading) != 1:
        raise RenderError("TFR must have exactly one canonical routing-policy section")
    return markdown_section(canonical, heading, source)


def coding_behavior_policy(root: Path) -> str:
    """Share the canonical coding behavior only with Kael and Kovan."""
    source = root / "olympus" / "policies" / "routing.md"
    canonical = read_text(source)
    heading = "## Coding behavior"
    if canonical.count(heading) != 1:
        raise RenderError("coding behavior must have exactly one canonical routing-policy section")
    return markdown_section(canonical, heading, source)


def add_yaml_comment(header: str, message: str) -> str:
    if not header.startswith("---\n") or not header.endswith("\n---\n"):
        raise RenderError("OpenCode agent metadata must be a YAML frontmatter block")
    return header.replace("---\n", f"---\n# {message}\n", 1)


def add_markdown_comment(text: str, message: str) -> str:
    text = text.removeprefix("\ufeff")
    if text.startswith("---"):
        frontmatter = re.match(r"\A---\n.*?^---[ \t]*(?:\n|$)", text, re.MULTILINE | re.DOTALL)
        if frontmatter is None:
            raise RenderError("Markdown YAML frontmatter must start with --- and close with ---")
        return text[: frontmatter.end()] + f"<!-- {message} -->\n" + text[frontmatter.end() :]
    return f"<!-- {message} -->\n" + text


def prefix_yaml_description(text: str, identity: str, source: Path) -> str:
    match = re.search(r"(?m)^description:[ \t]*(.*?)[ \t]*$", text)
    if match is None:
        raise RenderError(f"OpenCode metadata has no description field: {source}")
    try:
        description = json.loads(match.group(1)) if match.group(1).startswith('"') else match.group(1)
    except json.JSONDecodeError as error:
        raise RenderError(f"invalid OpenCode description in {source}: {error}") from error
    rendered = "description: " + json.dumps(f"{identity}. {description}", ensure_ascii=False)
    return text[: match.start()] + rendered + text[match.end() :]


def _parallel_guidance(children: int) -> str:
    word = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}[children]
    if children == 1:
        return (
            "NORMAL is cost/context-aware: adapt from zero to one child, preferring the\n"
            "minimum useful parallelism. Use zero for direct answers and one for\n"
            "ordinary delegated work; keep child work sequential rather than splitting\n"
            "independent work across concurrently active children."
        )
    if children == 2:
        return (
            "NORMAL is cost/context-aware: adapt from zero to two children, preferring the\n"
            "minimum useful parallelism. Use zero for direct answers, one for ordinary\n"
            "delegated work, and two for common independent work only where both are useful."
        )
    if children == 4:
        return (
            "NORMAL is cost/context-aware: adapt from zero to four children, preferring the\n"
            "minimum useful parallelism. Use zero for direct answers, one for ordinary\n"
            "delegated work, two for common independent work, and three or four only where\n"
            "genuinely independent workstreams justify them. Before adding a concurrent child,\n"
            "check that its distinct responsibility or independent batch partition can progress\n"
            "without waiting, does not needlessly duplicate work, has clear result/integration\n"
            "ownership, and yields meaningful latency or context benefit. Do not narrate this\n"
            "check verbosely to the user."
    )
    if children > 4:
        values = [
            {3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}[count]
            for count in range(3, children + 1)
        ]
        upper = ", ".join(values[:-1]) + ", or " + values[-1]
    else:
        upper = "three"
    return (
        f"NORMAL is cost/context-aware: adapt from zero to {word} children, preferring the\n"
        "minimum useful parallelism. Use zero for direct answers, one for ordinary\n"
        f"delegated work, two for common independent work, and {upper} only where\n"
        "genuinely independent workstreams justify them. Before adding a concurrent child,\n"
        "check that its distinct responsibility or independent batch partition can progress\n"
        "without waiting, does not needlessly duplicate work, has clear result/integration\n"
        "ownership, and yields meaningful latency or context benefit. Do not narrate this\n"
        "check verbosely to the user."
    )


def opencode_outputs(root: Path, models: dict, policies: dict, identities: dict[str, str],
                     roles: set[str], max_children: int | None = None) -> dict[Path, str]:
    adapter = root / "olympus" / "harnesses" / "opencode"
    maintenance_policy_path = root / "olympus" / "policies" / "maintenance-context.md"
    maintenance_policy = read_text(maintenance_policy_path).strip()
    tfr_policy = focused_testing_policy(root)
    coding_policy = coding_behavior_policy(root)
    coding_roles = {"kael", "kovan"}
    metadata_dir = adapter / "agent-metadata"
    prompts_dir = adapter / "agent-prompts"
    metadata_roles = {path.stem for path in metadata_dir.glob("*.md") if path.is_file()}
    prompt_roles = {path.stem for path in prompts_dir.glob("*.md") if path.is_file()}
    if metadata_roles != roles or prompt_roles != roles:
        raise RenderError(
            "OpenCode adapter must have one metadata block and prompt for every canonical role; "
            f"metadata missing={sorted(roles - metadata_roles)}, prompts missing={sorted(roles - prompt_roles)}, "
            f"unexpected={sorted((metadata_roles | prompt_roles) - roles)}"
        )

    children = policies["max_children"] if max_children is None else max_children
    if type(children) is not int or not 1 <= children <= 8:
        raise RenderError("effective max_children must be an integer from 1 to 8")
    word = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}.get(children)
    if word is None:
        raise RenderError("max_children outside supported word mapping (1..8)")
    output: dict[Path, str] = {}
    for role in sorted(roles):
        metadata_path = metadata_dir / f"{role}.md"
        prompt_path = prompts_dir / f"{role}.md"
        model, effort = role_model(models, role)
        values = {"opencode_model": model, "effort": effort}
        metadata = prefix_yaml_description(replace_tokens(read_text(metadata_path), values, metadata_path), identities[role], metadata_path)
        prompt_source = read_text(prompt_path)
        # Only the root orchestrator receives the shared testing policy.
        if role == "kael" and prompt_source.count("{{tfr_policy}}") != 1:
            raise RenderError("OpenCode Kael prompt must contain one TFR policy token")
        if role != "kael" and "{{tfr_policy}}" in prompt_source:
            raise RenderError("TFR root policy token is reserved for OpenCode Kael")
        if role in coding_roles and prompt_source.count("{{coding_behavior_policy}}") != 1:
            raise RenderError(f"OpenCode {role.title()} prompt must contain one coding behavior policy token")
        if role not in coding_roles and "{{coding_behavior_policy}}" in prompt_source:
            raise RenderError("coding behavior policy token is reserved for OpenCode Kael and Kovan")
        prompt = replace_tokens(
            prompt_source,
            {
                "max_children": children,
                "max_children_word": word,
                "max_children_plural": "" if children == 1 else "ren",
                "max_children_s": "" if children == 1 else "s",
                "max_children_title": word.title(),
                "normal_parallelism_guidance": _parallel_guidance(children),
                "display_identity": identities[role],
                "tfr_policy": tfr_policy if role == "kael" else "",
                "coding_behavior_policy": coding_policy if role in coding_roles else "",
                "maintenance_context_policy": maintenance_policy if role == "kael" else "",
            },
            prompt_path,
        )
        display = identities[role]
        header = add_yaml_comment(metadata, f"{GENERATED} Canonical Olympus role: olympus/roles/{role}.md ({display}).")
        output[root / ".opencode" / "agents" / f"{role}.md"] = header + prompt

    config_path = adapter / "config.jsonc"
    config = replace_tokens(
        read_text(config_path),
        {"opencode_kael_model": role_model(models, "kael")[0]},
        config_path,
    )
    output[root / "opencode.jsonc"] = config.replace("{\n", f"{{\n  // {GENERATED}\n", 1)

    display_names = "\n".join(f'  {role}: {json.dumps(identities[role], ensure_ascii=False)},' for role in sorted(roles))
    for source_name, output_path, comment in (
        ("activity.ts", root / ".opencode" / "plugins" / "olympus-activity" / "activity.ts", f"// {GENERATED}\n"),
        ("tui.tsx", root / ".opencode" / "plugins" / "olympus-activity" / "tui.tsx", f"// {GENERATED}\n"),
    ):
        source_path = adapter / source_name
        body = read_text(source_path)
        if source_name == "activity.ts":
            marker = "// {{display_names}}"
            if body.count(marker) != 1:
                raise RenderError(f"expected exactly one commented display_names marker in {source_path}")
            body = replace_tokens(body.replace(marker, "{{display_names}}"), {"display_names": display_names}, source_path)
        output[output_path] = add_markdown_comment(body, GENERATED) if source_name.endswith(".md") else comment + body
    setup_source = adapter / "worktree-setup.ps1"
    output[root / ".opencode" / "scripts" / "worktree-setup.ps1"] = f"# {GENERATED}\n" + read_text(setup_source)
    commands_dir = adapter / "commands"
    for command in ("olympus.ultra", "olympus.performance", "olympus.performance-ultra"):
        source_path = commands_dir / f"{command}.md"
        command_text = read_text(source_path)
        if not command_text.startswith("---\n"):
            raise RenderError(f"OpenCode command metadata must be a YAML frontmatter block: {source_path}")
        output[root / ".opencode" / "commands" / f"{command}.md"] = add_markdown_comment(command_text, GENERATED)
    return output


def capability_doc(capabilities: dict) -> str:
    lines = [
        "<!-- " + GENERATED + " Source: olympus/harnesses/capabilities.toml. -->",
        "# Olympus harness capability contract",
        "",
        "`SUPPORTED`, `ADAPTABLE`, `PARTIAL`, `GAP`, and `NOT_NEEDED` describe the capability represented through each adapter and the scope of its evidence—not a blanket guarantee of native runtime behavior. `SUPPORTED` means Olympus represents the capability through an adapter mechanism; see the [per-capability evidence](HARNESSES.md#capability-evidence) for its limits. Adapter limits do not change or weaken Core policy.",
        "",
        "| Capability | OpenCode |",
        "|---|---|",
    ]
    for capability in CAPABILITIES:
        lines.append(f"| `{capability}` | {capabilities['opencode'][capability]} |")
    lines.extend(
        [
            "",
            "Global install file placement and global runtime discovery are separate claims. `GLOBAL_RUNTIME_DISCOVERY = GAP` means an isolated runtime omitted required global agents; `PARTIAL` means evidence is incomplete or inconclusive; `SUPPORTED` records isolated paths and the expected roster only within the version/platform scope in the [evidence table](HARNESSES.md#capability-evidence). It does not imply every platform, public installation path, or model execution.",
            "",
        ]
    )
    return "\n".join(lines)


def outputs_for(root: Path, selected: str, max_children: int | None = None) -> dict[Path, str]:
    if selected != "opencode":
        raise RenderError(f"unsupported harness selector: {selected!r}; only 'opencode' is supported")
    models, policies, _, identities, roles = checked_sources(root)
    return opencode_outputs(root, models, policies, identities, roles, max_children)


def rendered_kael(root: Path, max_children: int) -> str:
    outputs = outputs_for(root, "opencode", max_children)
    return outputs[root / ".opencode" / "agents" / "kael.md"]


def rendered_primaries(root: Path, max_children: int) -> dict[str, str]:
    outputs = outputs_for(root, "opencode", max_children)
    return {
        role: outputs[root / ".opencode" / "agents" / f"{role}.md"]
        for role in ("kael", "atlas")
    }


def _absolute_path(path: Path) -> Path:
    return Path(os.path.abspath(path))


def _is_within(path: Path, boundary: Path) -> bool:
    path_text = os.path.normcase(os.path.abspath(path))
    boundary_text = os.path.normcase(os.path.abspath(boundary))
    try:
        return os.path.commonpath((boundary_text, path_text)) == boundary_text
    except ValueError:
        return False


def _paths_overlap(left: Path, right: Path) -> bool:
    return _is_within(left, right) or _is_within(right, left)


def _is_link(metadata: os.stat_result) -> bool:
    reparse_point = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return stat.S_ISLNK(metadata.st_mode) or bool(getattr(metadata, "st_file_attributes", 0) & reparse_point)


def _validate_output_path(path: Path, *, directory: bool, boundary: Path | None = None) -> None:
    path = _absolute_path(path)
    if boundary is not None and not _is_within(path, boundary):
        raise RenderError(f"candidate output escapes --output-root: {path}")

    components = [Path(path.anchor)]
    current = components[0]
    for part in path.parts[1:]:
        current /= part
        components.append(current)

    for index, component in enumerate(components):
        try:
            metadata = component.lstat()
        except FileNotFoundError:
            continue
        except OSError as error:
            raise RenderError(f"cannot inspect candidate output path {component}: {error}") from error

        if _is_link(metadata):
            raise RenderError(f"refusing candidate output through symlink or reparse point: {component}")

        is_final = index == len(components) - 1
        if not is_final or directory:
            if not stat.S_ISDIR(metadata.st_mode):
                raise RenderError(f"candidate output parent is not a directory: {component}")
        elif not stat.S_ISREG(metadata.st_mode):
            raise RenderError(f"candidate output is not a regular file: {component}")
        elif metadata.st_nlink > 1:
            raise RenderError(f"refusing hardlinked candidate output: {component}")


def _candidate_output_paths(
    source_root: Path, destination_root: Path, resolved_destination: Path, output: dict[Path, str]
) -> dict[Path, str]:
    candidate: dict[Path, str] = {}
    for source_path, content in output.items():
        try:
            relative = source_path.relative_to(source_root)
        except ValueError as error:
            raise RenderError(f"managed output is outside source root: {source_path}") from error
        if relative.is_absolute() or ".." in relative.parts:
            raise RenderError(f"invalid managed output path: {source_path}")
        path = destination_root / relative
        _validate_output_path(path, directory=False, boundary=destination_root)
        try:
            resolved_path = path.resolve()
        except OSError as error:
            raise RenderError(f"cannot resolve candidate output path {path}: {error}") from error
        if not _is_within(resolved_path, resolved_destination):
            raise RenderError(f"candidate output escapes --output-root: {path}")
        candidate[path] = content
    return candidate


def _has_generated_header(path: Path, namespace: Path) -> bool:
    # Look for the exact renderer comment in a generated header position, not
    # a mention of it in a customized prompt or source file.
    lines = path.read_bytes().decode("utf-8", errors="replace").splitlines()
    if not lines:
        return False
    if namespace.name == "agents":
        if len(lines) < 3 or lines[0] != "---":
            return False
        return re.fullmatch(
            rf"# {re.escape(GENERATED)}(?: Canonical Olympus role: olympus/roles/[^/]+\.md \(.+\)\.)?",
            lines[1],
        ) is not None
    if namespace.name == "commands":
        if lines[0] != "---":
            return False
        end = next((i for i in range(1, len(lines)) if lines[i].rstrip(" \t") == "---"), len(lines))
        return lines[end + 1 : end + 2] == [f"<!-- {GENERATED} -->"]
    prefix = "#" if namespace.name == "scripts" else "//"
    return lines[0] == f"{prefix} {GENERATED}"


def _obsolete_outputs(root: Path, output: dict[Path, str]) -> dict[Path, Path]:
    obsolete = {}
    for namespace, suffixes in OPENCODE_OUTPUT_NAMESPACES.items():
        directory = root / namespace
        _validate_output_path(directory, directory=True, boundary=root)
        try:
            candidates = list(directory.iterdir())
        except FileNotFoundError:
            continue
        except OSError as error:
            raise RenderError(f"cannot enumerate candidate namespace {directory}: {error}") from error
        try:
            for path in candidates:
                if path.suffix.casefold() not in suffixes or path in output:
                    continue
                metadata = path.lstat()
                # Do not open custom links, devices, directories or hardlinks.
                if _is_link(metadata) or not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
                    continue
                if _has_generated_header(path, namespace):
                    obsolete[path] = namespace
        except OSError as error:
            raise RenderError(f"cannot inspect candidate namespace {directory}: {error}") from error
    return obsolete


def run(root: Path, action: str, selected: str, output_root: Path | None = None) -> int:
    if output_root is None:
        source_root = root
        destination_root = root
        resolved_destination = root.resolve()
    else:
        source_root = root.resolve()
        destination_root = _absolute_path(output_root)
        _validate_output_path(destination_root, directory=True)
        try:
            resolved_destination = destination_root.resolve()
        except OSError as error:
            raise RenderError(f"cannot resolve --output-root {destination_root}: {error}") from error
        if _paths_overlap(source_root, resolved_destination):
            raise RenderError("--output-root must not overlap the source root")

    output = outputs_for(source_root, selected)
    capabilities = checked_sources(source_root)[2]
    output[source_root / "docs" / "HARNESS-CAPABILITIES.md"] = capability_doc(capabilities)
    output = _candidate_output_paths(source_root, destination_root, resolved_destination, output)
    obsolete = _obsolete_outputs(destination_root, output)

    changes = []
    for path in sorted(output, key=lambda item: item.relative_to(destination_root).as_posix().casefold()):
        rel = path.relative_to(destination_root).as_posix()
        expected = output[path]
        exists = path.is_file()
        actual = read_text(path) if exists else None
        if actual != expected:
            changes.append((path, rel, "drift" if exists else "missing", expected))

    if action == "check":
        if changes or obsolete:
            for _, rel, state, _ in changes:
                print(f"DRIFT {state}: {rel}")
            for path in sorted(obsolete):
                print(f"DRIFT obsolete: {path.relative_to(destination_root).as_posix()}")
            print(f"HARNESS_RENDER_CHECK: FAIL ({len(changes) + len(obsolete)} mismatch(es))")
            return 1
        print(f"HARNESS_RENDER_CHECK: PASS ({selected}; {len(output)} managed output(s); read-only)")
        return 0

    # All sources and expected content were validated before the first write.
    for path, _, _, expected in changes:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding="utf-8", newline="\n")
    for path, namespace in sorted(obsolete.items()):
        try:
            _validate_output_path(path, directory=False, boundary=destination_root)
            if not _has_generated_header(path, namespace):
                raise RenderError(f"obsolete output no longer has a generated header: {path}")
            path.unlink()
        except OSError as error:
            raise RenderError(f"cannot prune obsolete output {path}: {error}") from error
    print(f"HARNESS_RENDER: PASS ({selected}; wrote {len(changes)} changed output(s), "
          f"{len(output) - len(changes)} unchanged; pruned {len(obsolete)} obsolete output(s))")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("render", "check", "kael", "primaries"),
                        help="render managed output, check drift, or print cap-specific primary prompt(s)")
    parser.add_argument("--harness", choices=("opencode",), default="opencode")
    parser.add_argument("--root", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--output-root", type=Path,
                        help="use an isolated candidate destination for render/check")
    parser.add_argument("--max-children", type=int, choices=range(1, 9), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = (args.root or Path(__file__).resolve().parents[1]).resolve()
    try:
        if args.action in {"kael", "primaries"}:
            if args.output_root is not None:
                parser.error("--output-root is only supported with render/check")
            if args.max_children is None:
                parser.error(f"{args.action} requires --max-children")
            if hasattr(sys.stdout, "reconfigure"):
                sys.stdout.reconfigure(encoding="utf-8", newline="")
            if args.action == "kael":
                sys.stdout.write(rendered_kael(root, args.max_children))
            else:
                sys.stdout.write(json.dumps(rendered_primaries(root, args.max_children), ensure_ascii=False))
            return 0
        return run(root, args.action, args.harness, args.output_root)
    except RenderError as error:
        print(f"HARNESS_RENDER: ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())

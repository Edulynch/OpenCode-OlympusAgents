[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$approvedTempRoot = Join-Path ([IO.Path]::GetFullPath([IO.Path]::GetTempPath())) 'opencode'
$runRoot = Join-Path $approvedTempRoot ('bootstrap-source-validation-' + [guid]::NewGuid().ToString('N'))
$originalPath = [Environment]::GetEnvironmentVariable('PATH','Process')
$utf8 = [Text.UTF8Encoding]::new($false)
$createdRunRoot = $false

function Assert-Condition([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw $Message }
}

function New-SourceFixture([string]$Name) {
    $source = Join-Path $runRoot $Name
    [IO.Directory]::CreateDirectory($source) | Out-Null
    Copy-Item -LiteralPath (Join-Path $repoRoot '.opencode') -Destination $source -Recurse
    Copy-Item -LiteralPath (Join-Path $repoRoot 'opencode.jsonc') -Destination $source
    $scripts = Join-Path $source 'scripts'
    [IO.Directory]::CreateDirectory($scripts) | Out-Null
    Copy-Item -LiteralPath (Join-Path $repoRoot 'scripts/bootstrap.ps1') -Destination $scripts
    return $source
}

function New-Target([string]$Name) {
    $target = Join-Path $runRoot $Name
    [IO.Directory]::CreateDirectory($target) | Out-Null
    [IO.File]::WriteAllText((Join-Path $target 'README.md'), "source-validation fixture`n", $utf8)
    & git -C $target init --quiet
    if ($LASTEXITCODE -ne 0) { throw 'Fixture Git init failed.' }
    & git -C $target -c user.name=Qualification -c user.email=qualification@example.invalid add -- README.md
    if ($LASTEXITCODE -ne 0) { throw 'Fixture Git add failed.' }
    & git -C $target -c user.name=Qualification -c user.email=qualification@example.invalid commit --quiet -m fixture
    if ($LASTEXITCODE -ne 0) { throw 'Fixture Git commit failed.' }
    return $target
}

function Get-SpecKitHashes([string]$Source) {
    $commands = Join-Path $Source '.opencode/commands'
    $files = @(Get-ChildItem -LiteralPath $commands -Filter 'speckit.*.md' -File -Force | Sort-Object FullName)
    Assert-Condition ($files.Count -gt 0) 'SpecKit fixture commands are absent.'
    $hashes = [ordered]@{}
    foreach ($file in $files) {
        $text = [IO.File]::ReadAllText($file.FullName)
        Assert-Condition ($text -notmatch 'GENERATED BY scripts/render_harnesses\.py') ('SpecKit fixture unexpectedly has the managed marker: ' + $file.Name)
        $relative = $file.FullName.Substring($Source.Length + 1).Replace('\', '/')
        $hashes[$relative] = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash
    }
    return $hashes
}

function Assert-SpecKitUnchanged([string]$Source, $Expected) {
    foreach ($relative in $Expected.Keys) {
        $path = Join-Path $Source ($relative -replace '/', [IO.Path]::DirectorySeparatorChar)
        Assert-Condition (Test-Path -LiteralPath $path -PathType Leaf) ('Unmanaged SpecKit file disappeared: ' + $relative)
        Assert-Condition ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ceq $Expected[$relative]) ('Unmanaged SpecKit file changed: ' + $relative)
    }
}

function Invoke-DryRun([string]$Source, [string]$Target) {
    $pwsh = Join-Path $PSHOME 'pwsh.exe'
    $bootstrap = Join-Path $Source 'scripts/bootstrap.ps1'
    $output = @(& $pwsh -NoProfile -File $bootstrap -Target $Target -DryRun 2>&1)
    [pscustomobject]@{ ExitCode=[int]$LASTEXITCODE; Text=($output | Out-String) }
}

try {
    if (-not (Get-Command git -ErrorAction SilentlyContinue)) { throw 'Git is unavailable.' }
    if (-not (Test-Path -LiteralPath $approvedTempRoot -PathType Container)) { throw 'Approved opencode temporary directory is unavailable.' }
    [IO.Directory]::CreateDirectory($runRoot) | Out-Null
    $createdRunRoot = $true

    $mockBin = Join-Path $runRoot 'mock-bin'
    [IO.Directory]::CreateDirectory($mockBin) | Out-Null
    Copy-Item -LiteralPath (Join-Path $repoRoot 'tests/release/fixtures/opencode.ps1') -Destination (Join-Path $mockBin 'opencode.ps1')
    $pwsh = Join-Path $PSHOME 'pwsh.exe'
    $wrapper = "@echo off`r`n`"$pwsh`" -NoProfile -File `"%~dp0opencode.ps1`" %*`r`nexit /b %ERRORLEVEL%`r`n"
    [IO.File]::WriteAllText((Join-Path $mockBin 'opencode.cmd'), $wrapper, [Text.Encoding]::ASCII)
    $windowsApps = Join-Path $env:LOCALAPPDATA 'Microsoft/WindowsApps'
    $pathParts = @($originalPath -split [regex]::Escape([IO.Path]::PathSeparator) | Where-Object {
        $_ -and $_.Trim('"') -ine $windowsApps -and $_.Trim('"') -ine $PSHOME
    })
    $env:PATH = (@($mockBin,$PSHOME) + $pathParts) -join [IO.Path]::PathSeparator

    $validSource = New-SourceFixture 'valid-source'
    $foreignHashes = Get-SpecKitHashes $validSource
    $validTarget = New-Target 'valid-target'
    $valid = Invoke-DryRun $validSource $validTarget
    Assert-Condition ($valid.ExitCode -eq 0 -and $valid.Text -match '(?m)^DRY_RUN_READY\s*$') ('Unmanaged SpecKit commands were rejected: ' + $valid.Text)
    Assert-SpecKitUnchanged $validSource $foreignHashes
    $validTargetStatus = (& git -C $validTarget status --porcelain --untracked-files=all | Out-String).Trim()
    Assert-Condition (-not $validTargetStatus) ('Dry run changed the fixture target: ' + $validTargetStatus)
    Write-Output 'BOOTSTRAP_FOREIGN_SPECKIT: PASS (accepted as unmanaged; hashes unchanged)'

    $invalidSource = New-SourceFixture 'invalid-managed-source'
    $invalidTarget = New-Target 'invalid-target'
    $managedPath = Join-Path $invalidSource '.opencode/agents/vera.md'
    $managedText = [IO.File]::ReadAllText($managedPath)
    $damaged = $managedText.Replace('GENERATED BY scripts/render_harnesses.py', 'INVALIDATED BY focused regression')
    Assert-Condition ($damaged -cne $managedText) 'Regression could not locate the managed generated marker.'
    [IO.File]::WriteAllText($managedPath, $damaged, $utf8)
    $invalid = Invoke-DryRun $invalidSource $invalidTarget
    Assert-Condition ($invalid.ExitCode -ne 0 -and $invalid.Text -match 'SOURCE_INVALID') ('Invalid managed generated source was not rejected: ' + $invalid.Text)
    $invalidTargetStatus = (& git -C $invalidTarget status --porcelain --untracked-files=all | Out-String).Trim()
    Assert-Condition (-not $invalidTargetStatus) ('Rejected-source dry run changed the fixture target: ' + $invalidTargetStatus)
    Write-Output 'BOOTSTRAP_INVALID_MANAGED_SOURCE: PASS (SOURCE_INVALID; target unchanged)'
    Write-Output 'BOOTSTRAP SOURCE VALIDATION QUALIFICATION: PASS'
    exit 0
} catch {
    Write-Output ('BOOTSTRAP SOURCE VALIDATION QUALIFICATION: FAIL (' + $_.Exception.Message + ')')
    exit 1
} finally {
    [Environment]::SetEnvironmentVariable('PATH',$originalPath,'Process')
    if ($createdRunRoot -and (Test-Path -LiteralPath $runRoot)) {
        Remove-Item -LiteralPath $runRoot -Recurse -Force -ErrorAction SilentlyContinue
    }
}

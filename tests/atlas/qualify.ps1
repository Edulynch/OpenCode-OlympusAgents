    Check AT19 ($a -match 'NO_PROGRESS:' -and $k -match 'NO_PROGRESS:')
    Check AT20 ($k -match 'reconcile the known original worker' -and $k -match 'COMPLETION_UNCONFIRMED' -and $k -match 'No blind replacement')
